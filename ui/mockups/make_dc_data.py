"""Rebuild dc-data.js from the body catalogue.

The mockups load the catalogue as a canvas asset (/_blob/<id>). Offline,
support.js answers that URL from window.DC_ASSETS, which this script writes.
Run from this folder: python3 make_dc_data.py  (standard library only)
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'data', 'solar-system', 'bodies.csv')
OUT = os.path.join(HERE, 'dc-data.js')
ASSET_ID = '3b5340be21b1b3b1172132afa307251e'  # the asset id Main.dc.html fetches

CATS = {'star': 0, 'planet': 1, 'dwarf_planet': 2, 'moon': 3, 'main_belt': 4, 'neo': 5, 'earth_coorbital': 5,
        'mars_trojan': 6, 'jupiter_trojan': 6, 'neptune_trojan': 6, 'centaur': 7, 'tno': 8, 'comet': 9,
        'main_belt_comet': 9}


def num(x, digits=6):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return 0
    return float(f'{v:.{digits}g}')


def main():
    with open(SRC, encoding='utf-8') as fh:
        rows = list(csv.DictReader(fh))
    keep = [r for r in rows if not (r['category'] == 'moon' and num(r['radius_km']) < 5 and r['id'] not in ('phobos', 'deimos'))]
    idx = {r['id']: i for i, r in enumerate(keep)}
    out = []
    for r in keep:
        out.append([r['id'], r['name'], idx.get(r['parent'], -1), CATS[r['category']], num(r['radius_km'], 4),
                    num(r['gm_km3_s2'], 6), num(r['a_km'], 8), num(r['e'], 6), num(r['i_deg'], 6), num(r['node_deg'], 6),
                    num(r['argp_deg'], 6), num(r['mean_anomaly_deg'], 7), num(r['mean_motion_deg_day'], 8),
                    num(r['epoch_jd_tdb'], 9), num(r['node_rate_deg_day'], 6), num(r['argp_rate_deg_day'], 6),
                    num(r['soi_radius_km'], 4)])
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('// Generated by make_dc_data.py from data/solar-system/bodies.csv. Do not edit.\n')
        fh.write('window.DC_ASSETS = window.DC_ASSETS || {};\n')
        fh.write(f'window.DC_ASSETS["{ASSET_ID}"] = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
    print(f'{len(out)} bodies -> {OUT}')


if __name__ == '__main__':
    main()
